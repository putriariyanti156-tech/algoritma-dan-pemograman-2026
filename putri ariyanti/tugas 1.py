# Program Menghitung Luas dan Keliling Taman Persegi Panjang

# Input
panjang = 20
lebar = 12

# Proses
luas = panjang * lebar
keliling = 2 * (panjang + lebar)

# Output
print("Panjang taman =", panjang, "meter")
print("Lebar taman =", lebar, "meter")
print("Luas taman =", luas, "m²")
print("Keliling taman =", keliling, "meter")